package com.raumanian.thirtysix.browser.core.presentation.designsystem.component

/** Spec 019 — the three looks of [RoundIconButton] (design system IconButton component). */
enum class RoundIconStyle {
    /** White fill and hairline ring, standing alone on a surface (hub corners). */
    Ringed,

    /** No fill, no ring, inside a bar that already groups its buttons. */
    Bare,

    /** Translucent glass on the hero or a card image. */
    Glass,
}
